"""Markdown renderer for VERIFICATION_AUDIT.md.

Called by the Celery worker after the sandbox run finishes. The output goes
to two places:

    1. Emailed to the candidate (as rendered HTML — see app/services/email.py)
    2. Committed back to the candidate's repo as VERIFICATION_AUDIT.md

Both targets re-parse the markdown independently. That's why the security
posture here (HTML escaping) matters even though the raw report is plain
text — see the note near html.escape() below.

Not handled here: per-test telemetry (durations, pass/fail). That goes to
the test_results table separately and is exposed via the Passport API. This
file only renders the human-readable prose summary.
"""

import html
from datetime import datetime, timezone


def generate_markdown_report(
    submission_id: str,
    challenge_title: str,
    is_passed: bool,
    logs: str,
) -> str:
    # Status emoji renders correctly in both GitHub and email HTML. Plain
    # "PASSED"/"FAILED" would also work, but the emoji gives a colour cue
    # that survives text-only fallbacks (email previews, terminal viewers).
    status_emoji = "✅ PASSED" if is_passed else "❌ FAILED"

    # UTC timestamp of the *sandbox run*, not the verification. They can be
    # days apart — a submission can pass tests today and be verified next
    # week. This is the run date on the report; verification date lives on
    # the submission row (verified_at) and appears on the Passport.
    timestamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")

    # --- HTML escaping ---
    # Escaped here, before the f-string template, so the raw entities land
    # inside the ```text fenced block. Two consumers re-parse this markdown:
    #
    #   - email.py runs markdown.markdown() on the full report. The markdown
    #     library passes raw HTML through by default, so an unescaped
    #     "<script>" in candidate stdout would become a live script tag in
    #     the email HTML — stored XSS in the recipient's mail client.
    #
    #   - GitHub renders the pushed .md file. Code-fenced content isn't
    #     interpreted as HTML there, so escaping is technically redundant on
    #     that path — but harmless.
    #
    # Side effect: a candidate whose code prints "a < b" will see "a &lt; b"
    # in the fenced block on GitHub, because the escape happens before the
    # code fence. Slightly ugly, but the alternative (escaping only for the
    # email path) means maintaining two versions of the same report.
    safe_logs = html.escape(logs)

    # Every interpolated value here is either a UUID, an admin-controlled
    # challenge title, or a value we escaped above. No user-supplied text is
    # inserted unescaped into the markdown structure. If you add a field,
    # escape it too — the markdown template is not a safe insertion context.
    report = f"""# Verification Audit Report

**Submission ID:** `{submission_id}`
**Challenge:** {challenge_title}
**Date:** {timestamp}
**Status:** {status_emoji}

---

## Execution Logs

```text
{safe_logs}
```

---
*This report was automatically generated by the Verification verification engine.*
*To dispute this result, please contact support.*
"""
    return report


# Deferred on purpose, not forgotten:
#
# - Commit SHA missing from the report. A candidate who pushed twice while
#   the sandbox was running gets a report that looks like it describes the
#   latest push, but actually describes whichever commit was in `after` when
#   the webhook fired. Adding "**Commit:** `{sha[:7]}`" to the header would
#   make the mismatch visible at a glance. It's a one-line change; deferred
#   because it requires threading commit_sha through the worker -> report
#   call chain, which touches more files than the fix is worth right now.
#
# - Log truncation happens upstream, not here. sandbox.py cuts logs to the
#   last 1000 chars before returning. By the time this function sees them,
#   the "Output:" section is already capped — which is why there's no visible
#   truncation marker. The full logs are technically available in
#   report.json, but aren't currently surfaced in the rendered report.
#
# - No telemetry in the report. Per-test durations and pass/fail outcomes are
#   stored in test_results but not embedded in the markdown. The rationale is
#   that the Passport API can render them richer than a markdown table can.
#   Worth revisiting if candidates complain they can't see per-test timing
#   without logging into the dashboard.
#
# - "contact support" is a dead reference. There's no support email or link
#   here. When this goes to real candidates, either add a mailto: link or
#   remove the line entirely — a dead-end instruction reads as broken product.